-- Expiry after the initial check must roll back provisioning, not just return
-- false (the worker commits normal false responses to preserve revocations).
CREATE FUNCTION pg_temp.expiry_delay() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.username = 'oit.expired-during@example.test' THEN PERFORM pg_sleep(4); END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER expiry_delay BEFORE INSERT ON oidc_identity.identities
FOR EACH ROW EXECUTE FUNCTION pg_temp.expiry_delay();
SELECT pg_temp.expect_error($sql$SELECT oidc_identity.reconcile(pg_temp.request(
    '77777777-7777-7777-7777-777777777777','oit.expired-during@example.test','["lab.READ_ONLY"]',10)
    ||jsonb_build_object('expires_at',floor(extract(epoch FROM clock_timestamp()))::bigint+3))$sql$,
    '28000','expiry during reconciliation aborts writes');
SELECT pg_temp.assert_true(NOT EXISTS (SELECT FROM pg_roles WHERE rolname='oit.expired-during@example.test'),
    'expired provisioning role rolled back');

