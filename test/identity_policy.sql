CREATE FUNCTION pg_temp.assert_true(ok boolean, description text) RETURNS void
LANGUAGE plpgsql AS $$
BEGIN
    IF ok IS DISTINCT FROM true THEN RAISE EXCEPTION 'assertion failed: %', description; END IF;
END
$$;
CREATE FUNCTION pg_temp.expect_error(command text, expected_state text, description text)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    BEGIN
        EXECUTE command;
    EXCEPTION WHEN OTHERS THEN
        IF SQLSTATE = expected_state THEN RETURN; END IF;
        RAISE EXCEPTION 'unexpected SQLSTATE % in %: %', SQLSTATE, description, SQLERRM;
    END;
    RAISE EXCEPTION 'expected rejection: %', description;
END
$$;
CREATE FUNCTION pg_temp.request(subject text, username text, claims jsonb, sequence integer)
RETURNS jsonb LANGUAGE sql AS $$
    SELECT jsonb_build_object(
        'tenant_id','11111111-1111-1111-1111-111111111111',
        'object_id',subject,'username',username,
        'issued_at',floor(extract(epoch FROM transaction_timestamp()))::bigint - 1000 + sequence,
        'expires_at',floor(extract(epoch FROM transaction_timestamp()))::bigint + 3600,
        'roles',claims)
$$;

